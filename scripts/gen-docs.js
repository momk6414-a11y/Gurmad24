'use strict';
// Generates docs/API.md from the real route table, so the documentation can never drift from the code.
const fs = require('fs'); const os = require('os'); const path = require('path');
const { build } = require('../src/bootstrap');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'g24-docs-'));
const { app } = build({ DATA_DIR: dir, ADMIN_PASSWORD: 'DocsOnly12345', autoBackup: false, quiet: true, SEED_DEMO_DATA: 'false' });
const who = a => a === false ? 'public' : a === true ? 'any logged-in user' : a.join(', ');
let md = `# GURMAD 24 - API reference (generated)\n\nGenerated by \`npm run docs\` from the live route table (${app.routes.length} endpoints).\n\n` +
`**Conventions**\n- Base path \`/api\`. JSON in, JSON out (CSV for \`*.csv\` exports).\n- Authentication: httpOnly session cookie \`g24s\` set by \`POST /api/auth/login\`. No tokens in JavaScript.\n- State-changing requests must be same-origin with \`Content-Type: application/json\`.\n- Errors: \`{ "error": "code", "fields": { "field": "reason" } }\` with HTTP 400/401/402/403/404/409/413/415/429/501.\n- Money is integer cents; commission rates are basis points (100 = 1%).\n- All payments are **sandbox**; no real money moves. Emergency cases are **SIMULATION** only.\n\n`;
const groups = {};
for (const r of app.routes) { const g = r.pattern.split('/')[2] || 'misc'; (groups[g] = groups[g] || []).push(r); }
for (const [g, rs] of Object.entries(groups)) {
  md += `## ${g}\n\n| Method | Path | Access | Description |\n|---|---|---|---|\n`;
  for (const r of rs) md += `| ${r.method} | \`${r.pattern}\` | ${who(r.auth)} | ${r.summary} |\n`;
  md += '\n';
}
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'API.md'), md);
fs.rmSync(dir, { recursive: true, force: true });
console.log('docs/API.md written,', app.routes.length, 'endpoints');
